"""Generate logging stubs for every import the runtime doesn't implement yet.

Reads the import list from the recompiled code (ppc_recomp_shared.h) and the
GUEST_IMPORT(...) definitions in runtime/*.cpp, and writes stubs.gen.cpp.

usage: python -I gen_stubs.py <ppc dir> <runtime dir>
"""
import pathlib
import re
import sys

ppc_dir, runtime_dir = map(pathlib.Path, sys.argv[1:3])
imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", (ppc_dir / "ppc_recomp_shared.h").read_text())))

# GUEST_IMPORT(name) and helper macros built on it, like NET_FAIL(name)
definition = re.compile(r"\b(?:GUEST_IMPORT|NET_FAIL)\((\w+)\)")
implemented = set()
for src in runtime_dir.glob("*.cpp"):
    if src.name == "stubs.gen.cpp":
        continue
    implemented.update(definition.findall(src.read_text()))

missing = [name for name in imports if name not in implemented]
lines = [
    "// Generated by gen_stubs.py: logging stubs for imports not implemented yet.",
    '#include "guest.h"',
    "",
    "static void Stub(const char* name, std::atomic<int>& calls, PPCContext& ctx)",
    "{",
    "    if (calls++ < 5)",
    '        Log("STUB %s(%08X, %08X, %08X, %08X) from %08llX", name, ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, ctx.lr);',
    "    ctx.r3.u64 = 0;",
    "}",
    "",
]
for name in missing:
    lines.append(f'GUEST_IMPORT({name}) {{ static std::atomic<int> n; Stub("{name}", n, ctx); }}')
(runtime_dir / "stubs.gen.cpp").write_text("\n".join(lines) + "\n")
print(f"{len(imports)} imports: {len(imports) - len(missing)} implemented, {len(missing)} stubbed")
